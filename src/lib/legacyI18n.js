function getOrdinalSuffix(number) {
  const mod100 = number % 100
  if (mod100 >= 11 && mod100 <= 13) return 'th'

  const mod10 = number % 10
  if (mod10 === 1) return 'st'
  if (mod10 === 2) return 'nd'
  if (mod10 === 3) return 'rd'
  return 'th'
}

function preserveSpacing(source, translatedCore) {
  const leading = source.match(/^\s*/)?.[0] || ''
  const trailing = source.match(/\s*$/)?.[0] || ''
  return `${leading}${translatedCore}${trailing}`
}

function translateCore(core) {
  if (EXACT_TRANSLATIONS.has(core)) return EXACT_TRANSLATIONS.get(core)

  for (const [pattern, resolve] of PATTERN_TRANSLATIONS) {
    const match = core.match(pattern)
    if (match) return resolve(match)
  }

  let translated = core
  PARTIAL_TRANSLATIONS.forEach(([zh, en]) => {
    translated = translated.replaceAll(zh, en)
  })

  return translated
}

export function isEnglishLocale(locale) {
  return normalizeLocale(locale) === 'en-US'
}

export function pickLocale(locale, zh, en) {
  return isEnglishLocale(locale) ? en : zh
}

export function translateLegacyText(value, locale = DEFAULT_LOCALE) {
  if (!isEnglishLocale(locale) || value === null || value === undefined) return value

  const source = String(value)
  const core = source.trim().replace(/\s+/g, ' ')
  if (!core || !/[\u4e00-\u9fff]/.test(core)) return value

  const translated = translateCore(core)
  return translated === core ? value : preserveSpacing(source, translated)
}
