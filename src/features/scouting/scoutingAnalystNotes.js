function buildCurrentVerificationQuestions(player, locale) {
  const signals = player.performanceSignals || {}
  const stage = signals.stageValidation || {}
  const form = signals.form || {}
  const opponent = signals.opponentStrength || {}
  const pressure = opponent.pressureTest || {}
  const primaryUse = opponent.deploymentPlaybook?.recommendations?.primaryUse
  const stageDelta = asFiniteNumber(stage.adjustedDeltaPct)
  const recentDelta = asFiniteNumber(form.deltaPct)
  const schedule = asFiniteNumber(opponent.schedulePercentile)
  const questions = []

  if (locale === 'en-US') {
    questions.push(stage.eligible && stageDelta !== null
      ? Math.abs(stageDelta) < 8
        ? `Adjusted playoff output is broadly stable versus the earlier stage (${formatSignedPctValue(stageDelta)}). Does decision quality remain equally stable in decisive fights?`
        : `Adjusted playoff output changes ${formatSignedPctValue(stageDelta)} from the earlier stage. Which hero, positioning, resource or opponent-targeting change explains that movement?`
      : `The recent five-map window changes ${formatSignedPctValue(recentDelta)}. Does VOD show a real role change or only short-window variance?`)
    questions.push(primaryUse
      ? `${primaryUse.hero} on ${MAP_TYPE_LABELS[primaryUse.mapType]?.[locale] || primaryUse.mapType} is the leading eligible deployment cell at ${primaryUse.confidencePct}% confidence. Does the decision quality transfer outside that cell?`
      : 'No hero-map cell clears the evidence gate. Which controlled hero and map trials are needed before defining a preferred deployment?')
    questions.push(pressure.eligible
      ? `Against stronger opponents, adjusted output retains ${pressure.retentionPct}% across ${pressure.maps} maps. Which cooldown, positioning or target-selection pattern makes that signal repeatable?`
      : `Schedule strength is ${getPercentileRead(schedule, locale)}. What changes first when opponent pace and punish windows rise?`)
    return questions
  }

  if (locale === 'ko-KR') {
    questions.push(stage.eligible && stageDelta !== null
      ? Math.abs(stageDelta) < 8
        ? `보정 플레이오프 산출은 이전 단계와 대체로 비슷합니다(${formatSignedPctValue(stageDelta)}). 결정적인 교전에서도 판단 품질이 같은 수준으로 유지됩니까?`
        : `보정 플레이오프 산출은 이전 단계 대비 ${formatSignedPctValue(stageDelta)}입니다. 영웅, 위치, 자원, 상대 견제 중 무엇이 변화를 설명합니까?`
      : `최근 5개 전장 산출은 ${formatSignedPctValue(recentDelta)}입니다. 영상에서 실제 역할 변화인지 단기 변동인지 확인됩니까?`)
    questions.push(primaryUse
      ? `${primaryUse.hero}·${MAP_TYPE_LABELS[primaryUse.mapType]?.[locale] || primaryUse.mapType}가 신뢰도 ${primaryUse.confidencePct}%의 최상 기용 단위입니다. 이 판단 품질이 다른 영웅·전장에도 이전됩니까?`
      : '근거 기준을 통과한 영웅·전장 단위가 없습니다. 선호 기용을 정하기 전에 어떤 통제 테스트가 필요합니까?')
    questions.push(pressure.eligible
      ? `강한 상대 구간에서 ${pressure.maps}개 전장 기준 보정 산출 유지율은 ${pressure.retentionPct}%입니다. 어떤 쿨다운, 위치, 대상 선택이 이 신호를 반복 가능하게 만듭니까?`
      : `일정 강도는 ${getPercentileRead(schedule, locale)}입니다. 상대 템포와 처벌 기회가 커질 때 무엇이 먼저 변합니까?`)
    return questions
  }

  questions.push(stage.eligible && stageDelta !== null
    ? Math.abs(stageDelta) < 8
      ? `季后赛校正表现与前期基本持平（${formatSignedPctValue(stageDelta)}）；关键团战中的决策质量是否同样稳定？`
      : `季后赛校正表现相对前期变化 ${formatSignedPctValue(stageDelta)}；英雄选择、站位空间、资源供给和对手针对中，哪一项最能解释变化？`
    : `最近五图产出变化 ${formatSignedPctValue(recentDelta)}；录像中这是实际职责变化，还是短窗口波动？`)
  questions.push(primaryUse
    ? `${primaryUse.hero}／${MAP_TYPE_LABELS[primaryUse.mapType]?.[locale] || primaryUse.mapType}是当前最佳合格部署单元，置信度 ${primaryUse.confidencePct}%；离开该单元后，决策质量能否迁移？`
    : '当前没有英雄—地图单元通过证据门槛；定义优先部署前，需要进行哪些受控英雄与地图核验？')
  questions.push(pressure.eligible
    ? `面对强对手时，${pressure.maps} 图的校正表现保持率为 ${pressure.retentionPct}%；哪些技能、站位或目标选择让这一信号可以重复？`
    : `赛程强度为${getPercentileRead(schedule, locale)}；当对手节奏和惩罚窗口上升时，哪部分能力最先发生变化？`)
  return questions
}

function getDataDrivenAnalystNote(player, locale, archetype) {
  if (!player) return null
  const opponent = player.performanceSignals?.opponentStrength || {}
  const evidence = opponent.evidenceQuality || {}
  const stage = player.performanceSignals?.stageValidation || {}
  return {
    version: 'current-evidence-analyst-note-v2',
    archetype: archetype || getGeneratedArchetype(player, locale),
    managerSummary: buildManagerSummary(player, locale),
    verdict: buildCurrentVerdict(player, locale),
    tacticalHypothesis: buildCurrentTacticalHypothesis(player, locale),
    vodQuestions: buildCurrentVerificationQuestions(player, locale),
    evidenceBasis: {
      selectionScore: player.selection?.score ?? null,
      tier: player.tier || null,
      subroleRank: player.selection?.subroleSelectionRank || player.highSampleSubroleRank || null,
      subroleTotal: player.highSampleSubroleTotal || null,
      adjustedPercentile: opponent.adjustedPercentile ?? null,
      floorPercentile: opponent.performanceEnvelope?.floorPercentile ?? null,
      evidenceGrade: evidence.grade || null,
      evidenceConfidencePct: evidence.confidencePct ?? null,
      subroleConfidencePct: player.subroleEvidence?.confidencePct ?? null,
      schedulePercentile: opponent.schedulePercentile ?? null,
      stageAdjustedDeltaPct: stage.adjustedDeltaPct ?? null
    }
  }
}

export function getScoutingAnalystNote(playerId, locale = 'zh-CN', player = null) {
  if (!player) return null
  const resolvedLocale = ['zh-CN', 'en-US', 'ko-KR'].includes(locale) ? locale : 'zh-CN'
  const legacyNote = ANALYST_NOTES[playerId]
  const addedArchetype = ADDITIONAL_ARCHETYPES[playerId]
  const archetype = legacyNote?.archetype?.[resolvedLocale]
    || addedArchetype?.[resolvedLocale]
    || getGeneratedArchetype(player, resolvedLocale)
  return getDataDrivenAnalystNote(player, resolvedLocale, archetype)
}
