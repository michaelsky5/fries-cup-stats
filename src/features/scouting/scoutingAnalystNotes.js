function asFiniteNumber(value) {
  if (value === null || value === undefined || value === '') return null
  const number = Number(value)
  return Number.isFinite(number) ? number : null
}

function formatSignedPctValue(value) {
  const number = asFiniteNumber(value)
  if (number === null) return '—'
  return `${number > 0 ? '+' : ''}${number}%`
}

function getPercentileRead(value, locale) {
  const percentile = asFiniteNumber(value)
  if (percentile === null) return '—'
  const topPct = Math.max(1, Math.min(100, 101 - Math.round(percentile)))
  if (locale === 'en-US') return `top ${topPct}% in-position (P${Math.round(percentile)})`
  if (locale === 'ko-KR') return `동일 포지션 상위 ${topPct}%(P${Math.round(percentile)})`
  return `同位置前 ${topPct}%（P${Math.round(percentile)}）`
}

function getPlainPercentileRead(value, locale) {
  const percentile = asFiniteNumber(value)
  if (percentile === null) return '—'
  const topPct = Math.max(1, Math.min(100, 101 - Math.round(percentile)))
  if (locale === 'en-US') return `top ${topPct}% in-position`
  if (locale === 'ko-KR') return `동일 포지션 상위 ${topPct}%`
  return `同位置前 ${topPct}%`
}

function stripPercentileCode(value) {
  return String(value || '')
    .replace(/（P\d+）/g, '')
    .replace(/\s*\(P\d+\)/g, '')
}

